// BASAIR P96.5 QA025 — owner-only unsigned SHA256 asset gate; no signing/publishing.
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {dirname,join} from 'node:path';
import {fileURLToPath} from 'node:url';
const home=dirname(fileURLToPath(import.meta.url));
const data=x=>readFileSync(join(home,x));
const sha=b=>createHash('sha256').update(b).digest('hex');
const published=JSON.parse(data('release.json').toString('utf8'));
const old=JSON.parse(Buffer.from(published.payload,'base64').toString('utf8'));
const next=JSON.parse(data('P965-QA025-UNSIGNED-PAYLOAD-DRAFT.json').toString('utf8'));
assert.equal(old.id,'P96-AYAH-JUMP-MEANING-CLEANUP-024');
assert.equal(old.sequence,24);
assert.equal(next.id,'P96-AYAH-FIRST-SHADE-NO-JITTER-025');
assert.equal(next.sequence,25);
assert.equal(next.channel,'owner-qa');
assert.equal(next.minAppVersion,690);
assert.equal(next.assets.length,8);
assert.equal(new Set(next.assets.map(a=>a.path)).size,8);
assert.equal(next.assets.filter(a=>a.kind==='css').length,4);
assert.equal(next.assets.filter(a=>a.kind==='js').length,4);
const untouched=old.assets.filter(a=>next.assets.some(b=>a.path===b.path&&a.kind===b.kind&&a.size===b.size&&a.sha256===b.sha256));
assert.equal(untouched.length,6,'six QA024 assets must stay unchanged');
assert.equal(next.assets.some(a=>a.path==='p964-ayah-meaning.js'),false,'QA025 replaces, never double-runs QA024 JS');
assert.equal(next.assets.some(a=>a.path==='p964-ayah-meaning.css'),false,'QA025 CSS must replace QA024 CSS');
for(const asset of next.assets){
 assert.match(asset.path,/^[A-Za-z0-9_-]+\.(?:js|css)$/);
 const bytes=data(asset.path);
 assert.equal(bytes.length,asset.size,asset.path+' bytes');
 assert.equal(sha(bytes),asset.sha256,asset.path+' SHA-256');
}
const js=data('p965-selected-ayah-no-scroll.js').toString('utf8');
const css=data('p965-selected-ayah-no-scroll.css').toString('utf8');
const oldJS=data('p964-ayah-meaning.js').toString('utf8');
const oldCSS=data('p964-ayah-meaning.css').toString('utf8');
assert.ok(css.startsWith(oldCSS),'QA024 word cleanup + font/print CSS preserved byte-for-byte');
assert.ok(js.includes("P96.4 / QA024: life-cycle cleanup"));
assert.ok(js.includes('if(ok){pendingSelection=Date.now();stats.retarget++;try{var jump='));
assert.ok(!js.includes("line.style.setProperty('font-size'"),'Quran printed font not changed');
assert.ok(!css.includes('@font-face'),'no font loading or new typeface');
assert.ok(js.includes('p94Recovered:true'),'QA022 recovery remains intact');
assert.ok(js.includes('var natural=actualLineIndex(card);'),'QA023 native priority preserved');
assert.equal(next.assets.filter(a=>a.path.includes('p965-')).length,2,'only two new QA025 assets');
assert.ok(js.includes('selectedLine=choice.selectedLine(card,pg)'),'native-acknowledged chosen-verse highlight');
assert.ok(js.includes('nativeAtTap:'),'stale native highlight cannot cancel a backward ayah retarget');
const tail=js.slice(js.indexOf('/* BASAIR P96.4 / QA024'));
assert.ok(!tail.includes('scrollTo(')&&!tail.includes('scrollIntoView('),'no custom scroll commands in QA025');
assert.ok(css.includes('bq965-ayah-selected'),'provisional selected ayah marker');
console.log('PASS QA025 manifest: all 8 SHA256 assets validated, six QA024 unchanged, no added scroll or Quran font modification, no OTA publication.');
